-- JANKS Tailoring — client measurement & style profiles (CRM)
--
-- HOW TO RUN THIS (same as the bookings table — one time only):
--   1. https://supabase.com/dashboard/project/sreaowbmyklwmhhjtoaz/sql/new
--   2. Paste everything in this file
--   3. Click Run
--   4. Green "Success. No rows returned." means it worked.
--
-- This creates three tables:
--   crm_clients             — one row per client (name, contact, notes)
--   crm_profile_versions    — every measurement/style profile ever saved for
--                             that client, newest marked current — so nothing
--                             is overwritten, and you can see what changed
--   crm_client_photos       — reference photos attached to a client
-- ───────────────────────────────────────────────────────────────────────────

create table if not exists public.crm_clients (
  id            uuid primary key default gen_random_uuid(),
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),

  first_name    text not null,
  last_name     text,
  email         text,
  phone         text,

  height_cm     numeric,
  weight_kg     numeric,

  notes         text,
  archived      boolean not null default false
);

create index if not exists crm_clients_name_idx
  on public.crm_clients (last_name, first_name);

create index if not exists crm_clients_email_idx
  on public.crm_clients (email);

-- Every save creates a new version rather than overwriting the last one.
-- `data` holds the full profile as JSON — every garment's style choices and
-- measurements, body shape notes, embroidery details. Its shape is defined
-- in src/config/measurement-profile.ts, not by this table, so adding a new
-- field to that file needs no database change here.
create table if not exists public.crm_profile_versions (
  id            uuid primary key default gen_random_uuid(),
  client_id     uuid not null references public.crm_clients(id) on delete cascade,
  created_at    timestamptz not null default now(),
  created_by    text,                    -- admin email who saved it
  label         text,                    -- e.g. "Initial fitting", "Updated for wedding order"
  data          jsonb not null default '{}'::jsonb,
  is_current    boolean not null default true
);

create index if not exists crm_profile_versions_client_idx
  on public.crm_profile_versions (client_id, created_at desc);

-- Only one version per client should ever be current. Enforced here rather
-- than trusted to application code, so it can't drift even if a bug creeps in.
create unique index if not exists crm_profile_versions_one_current_idx
  on public.crm_profile_versions (client_id)
  where is_current;

create table if not exists public.crm_client_photos (
  id            uuid primary key default gen_random_uuid(),
  client_id     uuid not null references public.crm_clients(id) on delete cascade,
  created_at    timestamptz not null default now(),
  storage_path  text not null,           -- path inside the private "client-photos" bucket
  caption       text
);

create index if not exists crm_client_photos_client_idx
  on public.crm_client_photos (client_id);

-- ── SECURITY ───────────────────────────────────────────────────────────────
-- Same approach as the bookings table: Row Level Security is on, and no
-- public policy is created. The anonymous key your website's browser code
-- uses cannot read or write any of this. Only the server, holding the
-- service-role key, can — and every admin route checks the signed-in email
-- against ADMIN_EMAILS before it touches these tables at all.
--
-- This matters more here than almost anywhere else in the project: this data
-- is clients' body measurements and photographs.

alter table public.crm_clients          enable row level security;
alter table public.crm_profile_versions enable row level security;
alter table public.crm_client_photos    enable row level security;

-- Deliberately no "create policy" statements — locked to server-side only.

-- ── PHOTO STORAGE ────────────────────────────────────────────────────────────
-- A private bucket for client reference photos. "public: false" means a
-- direct URL to a photo does not work — every photo is served through a
-- short-lived signed link generated by the admin API, never a permanent
-- public address.

insert into storage.buckets (id, name, public)
values ('client-photos', 'client-photos', false)
on conflict (id) do nothing;

-- No storage.objects policies are added, for the same reason as above: only
-- the service-role key (used exclusively by admin API routes) can read or
-- write this bucket.
