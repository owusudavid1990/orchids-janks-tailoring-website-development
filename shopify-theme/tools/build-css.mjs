// Compile the prefixed Tailwind utility stylesheet for the JANKS Shopify theme.
//
//   npm run build:css          one-off build (minified)
//   npm run build:css -- --dev unminified, easier to read
//
// Input : tools/input.css        (tokens copied from the reference site + @source paths)
// Output: janks-theme/assets/janks-tw.css
//
// Why rem -> px: the theme is built on Dawn, which sets the root font size to 62.5% (10px).
// Tailwind's defaults are rem-based (designed for a 16px root), so every rem value would render
// ~37% too small. The reference site has a 16px root, so converting rem -> px (x16) reproduces
// its exact sizes regardless of what the page root is set to.
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const dev = process.argv.includes("--dev");
const tmp = path.join(here, ".tw-raw.css");
const out = path.join(here, "..", "janks-theme", "assets", "janks-tw.css");

const bin = path.join(here, "node_modules", ".bin", process.platform === "win32" ? "tailwindcss.cmd" : "tailwindcss");
const args = ["-i", path.join(here, "input.css"), "-o", tmp];
if (!dev) args.push("--minify");
const r = spawnSync(bin, args, { cwd: here, encoding: "utf8", shell: process.platform === "win32" });
if (r.status !== 0) { console.error(r.stdout, r.stderr); process.exit(r.status || 1); }

let css = fs.readFileSync(tmp, "utf8");
const px = (n) => { const v = parseFloat(n) * 16; return (Math.round(v * 1000) / 1000) + "px"; };
// The lookbehind keeps class selectors intact (e.g. `.jt\:text-\[clamp\(3\.5rem...` and `w-\[calc\(100\%-2rem\)\]`), which must
// still match the markup; only real declaration values are converted.
// Only innermost `{...}` declaration blocks are touched, so selectors and @media preludes (where rem is the
// browser's own 16px, not the page root) are left alone.
css = css.replace(/\{[^{}]*\}/g, (block) => block.replace(/(-?\d*\.?\d+)rem\b/g, (_, n) => px(n)));

// Shopify's theme-check/asset pipeline prefers a plain header comment
css = `/* JANKS utility stylesheet - generated by shopify-theme/tools/build-css.mjs. Do not edit by hand. */\n` + css;
fs.writeFileSync(out, css);
fs.rmSync(tmp, { force: true });
console.log(`janks-tw.css: ${(css.length / 1024).toFixed(1)} KB (${dev ? "dev" : "minified"}) -> ${path.relative(process.cwd(), out)}`);
